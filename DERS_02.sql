--TASK 1 
SELECT MANAGER_ID,COUNT (*) AS ISCI_SAYI 
FROM HR.EMPLOYEES 
GROUP BY MANAGER_ID
ORDER BY COUNT (*) DESC;

--TASK 2
SELECT COUNTRY_ID,COUNT (*) AS OFIS_SAYI 
FROM HR.LOCATIONS 
GROUP BY COUNTRY_ID
ORDER BY COUNT (*) DESC;

--TASK 3
SELECT FIRST_NAME,LAST_NAME,JOB_TITLE 
FROM HR.EMPLOYEES E
JOIN HR.JOBS J ON E.JOB_ID=J.JOB_ID;

--TASK 4
SELECT DEPARTMENT_ID,ROUND(AVG(SALARY),2) AS ORTA_MAAS
FROM HR.EMPLOYEES
GROUP BY DEPARTMENT_ID
HAVING AVG(SALARY)>8000;

--TASK 5
SELECT DEPARTMENT_ID,COUNT (*) AS ISCI_SAYI
FROM HR.EMPLOYEES
WHERE SALARY>=3000
GROUP BY DEPARTMENT_ID
HAVING COUNT(*)>3;

--TASK 6
SELECT JOB_TITLE,COUNT(*) AS ISCI_SAYI
FROM HR.EMPLOYEES E
JOIN HR.JOBS J ON E.JOB_ID=J.JOB_ID
GROUP BY JOB_TITLE
ORDER BY COUNT(*) DESC;

-- Task 7
SELECT L.CITY, L.COUNTRY_ID
FROM HR.LOCATIONS L
LEFT JOIN HR.DEPARTMENTS D ON L.LOCATION_ID = D.LOCATION_ID
WHERE D.LOCATION_ID IS NULL;

--TASK 8
-- Səhv 1: E.LAST_NAME SELECT-də idi, amma GROUP BY-da və aqreqat funksiyada yox idi.
-- Səhv 2: ON-da JOB_ID-nin qarşısında alias yox idi, sütun hər iki cədvəldə var. J.JOB_ID yazıldı.
-- Səhv 3: Aqreqat funksiya WHERE-də yazılmışdı. Şərt HAVING-ə keçirildi, GROUP BY-dan sonra.
SELECT J.JOB_TITLE, AVG(E.SALARY) AS ORTA_MAAS
FROM HR.EMPLOYEES E
JOIN HR.JOBS J ON E.JOB_ID = J.JOB_ID
GROUP BY J.JOB_TITLE
HAVING AVG(E.SALARY) > 10000;

--TASK 9
SELECT CITY,COUNT(*) AS ISCI_SAYI,ROUND(AVG(SALARY)) AS ORTA_MAAS
FROM HR.EMPLOYEES E
JOIN HR.DEPARTMENTS D ON E.DEPARTMENT_ID=D.DEPARTMENT_ID
JOIN HR.LOCATIONS L ON D.LOCATION_ID=L.LOCATION_ID
GROUP BY CITY
HAVING COUNT(*)>5
ORDER BY ISCI_SAYI DESC;

--TASK 10
SELECT DEPARTMENT_NAME,COUNT(E.FIRST_NAME) AS ISCI_SAYI
FROM HR.DEPARTMENTS D
LEFT JOIN HR.EMPLOYEES E ON D.DEPARTMENT_ID=E.DEPARTMENT_ID
GROUP BY D.DEPARTMENT_NAME
ORDER BY ISCI_SAYI DESC,D.DEPARTMENT_NAME;


